"""Generate the RTL and the test modules of one shard of the stress matrix.

The regular matrix is a selection; this one is the whole accepted space, split
into as many shards as there are machines.  Each shard generates its own RTL, its
own test modules and a manifest which `cocotb_runner` reads so that the modules it
runs are built and simulated the same way as the regular ones.

The test modules are generated rather than committed: there are 1752 of them and
they differ only in a dictionary.  A generated module asks the bench for the
complete set of vectors, which is the point of the stress matrix - the regular one
runs three frames, this one runs every shape a transform has to get right.

Run it with::

    python tools/stress_matrix.py --shard 0 --shards 20 --output build/stress

then::

    FFT_STRESS_MANIFEST=build/stress/manifest.json \\
    PYTHONPATH=build/stress pytest build/stress/stress_tests
"""

from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from pycde_example.fft import build_fft_system
from pycde_example.fft_matrix import full_configurations, shard

PACKAGE = "stress_tests"

BENCH_OF_STYLE = {
    "sdc": ("make_streaming_fft_tests",
            ["fft_result", "fft_handshake", "fft_backpressure"]),
    "mdc": ("make_mdc_tests", ["fft_result", "fft_handshake"]),
}

DEFAULT_BENCH = ("make_fft_tests", ["fft_result", "fft_handshake"])


def bench_for(config: dict) -> tuple[str, list[str]]:
    """The bench a configuration is tested with, and the names it returns.

    The two streaming topologies need their own bench: their chains are free
    running, so the spectra leave them a frame late and the frame based bench
    would compare each one with the wrong input.
    """
    params = config["params"]
    if params["eval_mode"] != "pipelined":
        return DEFAULT_BENCH
    return BENCH_OF_STYLE.get(params["pipeline_style"], DEFAULT_BENCH)


def module_of(config: dict) -> str:
    """The test module name of a configuration.

    It is derived from the name of the generated module, which is unique over the
    whole space, rather than from `test_module_name`, which drops the scaling and
    would collide.
    """
    return f"{PACKAGE}.test_{config['name'].lower()}"


def write_test_module(path: str, config: dict, bench: str,
                      names: list[str]) -> None:
    """Write the test module of one configuration."""
    params = dict(config["params"])
    returned = ", ".join(names)
    body = f'''"""Generated by tools/stress_matrix.py - do not edit.

{config["name"]}: the complete vector set through the RTL.
"""

from pycde_example.cocotb_runner import run_cocotb
from pycde_example.fft_tb import {bench}

params = {params!r}

{returned} = {bench}(**params, frames="complete")


def test_fft_runner():
    """Run the cocotb tests of this configuration."""
    run_cocotb(__name__)
'''
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(body)


def main() -> int:
    """Generate the shard."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--shard", type=int, default=0,
                        help="which shard to generate, counting from zero")
    parser.add_argument("--shards", type=int, default=1,
                        help="how many shards the space is split into")
    parser.add_argument("--output", default="build/stress",
                        help="where the test modules and the manifest go")
    parser.add_argument("--rtl", default="build/ip_fft_lib",
                        help="where the generated RTL goes")
    parser.add_argument("--list", action="store_true",
                        help="print the shard and stop, without generating")
    args = parser.parse_args()

    configs = list(full_configurations())
    mine = shard(configs, args.shard, args.shards)
    print(f"shard {args.shard} of {args.shards}: {len(mine)} of {len(configs)} "
          f"configurations")

    if args.list:
        for config in mine:
            print(f"  {config['name']}")
        return 0

    package = os.path.join(args.output, PACKAGE)
    os.makedirs(package, exist_ok=True)
    with open(os.path.join(package, "__init__.py"), "w", encoding="utf-8") as f:
        f.write('"""The test modules of one shard of the stress matrix."""\n')

    # the RTL: one PyCDE system per configuration, since a system has a single
    # top level module
    build_fft_system(configs=mine, output_directory=args.rtl)

    manifest = []
    for config in mine:
        bench, names = bench_for(config)
        module = module_of(config)
        write_test_module(os.path.join(package, module.split(".")[-1] + ".py"),
                          config, bench, names)
        manifest.append({
            "test_module": module,
            "rtl_name": config["name"],
            "rtl": config["rtl"],
            "params": config["params"],
        })

    manifest_path = os.path.join(args.output, "manifest.json")
    with open(manifest_path, "w", encoding="utf-8") as handle:
        json.dump(manifest, handle, indent=1)
    print(f"wrote {len(manifest)} test modules and {manifest_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
