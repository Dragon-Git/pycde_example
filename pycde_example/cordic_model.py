"""Bit exact software model of the configurable CORDIC.

This module is deliberately free of any PyCDE dependency: it is used by the
RTL generator (``cordic.py``) *and* by the tests, which allows the expected
results to be computed on the host without running a simulator.

Angle format
------------
Angles are two's complement fixed point numbers where ``pi`` is represented by
``1 << (width - 2)``.  The least significant bit of an angle therefore is
``pi / 2**(width - 2)`` radian.  The very same format is used by the original
``codic.py`` example (which used ``2**30`` for ``pi`` in a 32 bit datapath).
"""

from __future__ import annotations

import math

ROTATION = "rotation"
VECTORING = "vectoring"
MODES = (ROTATION, VECTORING)


def angle_scale(width: int) -> int:
    """Number of fixed point units of a full turn (``pi``)."""
    return 1 << (width - 2)


def angle_to_fixed(theta: float, width: int) -> int:
    """Convert an angle in radian into the fixed point format."""
    return round(theta * angle_scale(width) / math.pi)


def fixed_to_angle(value: int, width: int) -> float:
    """Convert a fixed point angle back into radian."""
    return value * math.pi / angle_scale(width)


def atan_table(width: int, iterations: int) -> list[int]:
    """``atan(2**-i)`` (i = 0 .. iterations-1) in the fixed point angle format."""
    scale = angle_scale(width)
    return [round(math.atan(2.0 ** -i) * scale / math.pi) for i in range(iterations)]


def wrap(value: int, width: int) -> int:
    """Truncate ``value`` to ``width`` bits, interpreting it as two's complement."""
    mask = (1 << width) - 1
    value &= mask
    if value & (1 << (width - 1)):
        value -= 1 << width
    return value


def cordic_gain(iterations: int) -> float:
    """The (uncompensated) gain of the CORDIC: ``prod(sqrt(1 + 2**-2i))``."""
    gain = 1.0
    for i in range(iterations):
        gain *= math.sqrt(1.0 + 4.0 ** -i)
    return gain


def cordic(x: int, y: int, z: int, width: int, iterations: int,
           mode: str = ROTATION) -> tuple[int, int, int]:
    """Bit exact model of the CORDIC datapath.

    The result is identical to the RTL generated by ``cordic.py`` (including the
    wrap around of the fixed point arithmetic and the truncation of the
    arithmetic shifts).
    """
    if mode not in MODES:
        raise ValueError(f"unknown CORDIC mode: {mode!r}")
    table = atan_table(width, iterations)
    for i in range(iterations):
        x_sh = x >> i
        y_sh = y >> i
        x_plus = wrap(x + y_sh, width)
        x_minus = wrap(x - y_sh, width)
        y_plus = wrap(y + x_sh, width)
        y_minus = wrap(y - x_sh, width)
        z_plus = wrap(z + table[i], width)
        z_minus = wrap(z - table[i], width)
        if mode == ROTATION:
            # The vector is rotated by +atan(2**-i) while z is positive, so
            # that the accumulated rotation ends up being z and z itself is
            # driven towards zero.
            q = 1 if z < 0 else 0
            x = x_plus if q else x_minus
            y = y_minus if q else y_plus
            z = z_plus if q else z_minus
        else:
            # Vectoring rotates the vector onto the x axis: while y is
            # positive the vector is rotated clockwise.
            q = 1 if y < 0 else 0
            x = x_minus if q else x_plus
            y = y_plus if q else y_minus
            z = z_minus if q else z_plus
    return x, y, z


def cordic_reference(x: float, y: float, z: float, iterations: int,
                     mode: str = ROTATION) -> tuple[float, float, float]:
    """The ideal (floating point) result of the same CORDIC operation."""
    gain = cordic_gain(iterations)
    if mode == ROTATION:
        cos_z = math.cos(z)
        sin_z = math.sin(z)
        return (gain * (x * cos_z - y * sin_z), gain * (x * sin_z + y * cos_z), 0.0)
    return (gain * math.hypot(x, y), 0.0, z + math.atan2(y, x))


def to_fixed(value: float, width: int) -> int:
    """Convert a real number into the two's complement fixed point format."""
    return round(value * (1 << (width - 1)))


def from_fixed(value: int, width: int) -> float:
    """Convert a two's complement fixed point number back into a real number."""
    return value / (1 << (width - 1))
